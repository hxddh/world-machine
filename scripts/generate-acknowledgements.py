#!/usr/bin/env python3
"""Writes the app's third-party notices from Cargo's own metadata.

`apps/world-machine-desktop/acknowledgements.tsv` lists every third-party
crate in `Cargo.lock` (every platform and feature, so the Mac, Windows and
Steam builds are all covered): its name, version, declared licence and
where its source lives. The app bundles the file at build time and shows it
in its Acknowledgements window.

The desktop test `tests/acknowledgements.rs` fails when `Cargo.lock` names
a crate the file does not, or the file names one the lock no longer has, so
a dependency change cannot land without running this again:

    python3 scripts/generate-acknowledgements.py          # rewrite the file
    python3 scripts/generate-acknowledgements.py --check  # fail if stale

It runs `cargo metadata --locked --all-features`, which may download the
sources of crates for other platforms the first time.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "apps/world-machine-desktop/acknowledgements.tsv"

HEADER = """\
# World Machine's third-party notices, generated by
# scripts/generate-acknowledgements.py from `cargo metadata` (do not edit).
# One crate a line: name, version, licence (as the crate declares it, SPDX),
# and where its source is. Every crate in Cargo.lock is listed, for every
# platform and feature.
# Fonts: none are bundled; the app draws with the system's own fonts.
# Sounds: none are bundled; every sound is synthesised by world-sound.
# Pictures: the app's art is World Machine's own (Apache-2.0).
"""


def clean(text: str | None) -> str:
    return " ".join((text or "").split()).replace("\t", " ")


def source_of(package: dict) -> str:
    repository = clean(package.get("repository"))
    if repository:
        return repository
    source = package.get("source") or ""
    if source.startswith("git+"):
        return source[len("git+") :].split("#", 1)[0]
    return f"https://crates.io/crates/{package['name']}"


def render() -> str:
    metadata = json.loads(
        subprocess.run(
            [
                "cargo",
                "metadata",
                "--format-version",
                "1",
                "--locked",
                "--all-features",
            ],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    rows = set()
    for package in metadata["packages"]:
        # Workspace members have no source: they are World Machine's own.
        if not package.get("source"):
            continue
        licence = clean(package.get("license"))
        if not licence and package.get("license_file"):
            licence = "see " + Path(package["license_file"]).name
        rows.add(
            (
                package["name"],
                package["version"],
                licence or "unknown",
                source_of(package),
            )
        )
    lines = ["\t".join(row) for row in sorted(rows)]
    return HEADER + "\n".join(lines) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    fresh = render()
    if check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != fresh:
            print(
                f"{OUTPUT.relative_to(ROOT)} is stale: run "
                "python3 scripts/generate-acknowledgements.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.write_text(fresh)
    unknown = [line for line in fresh.splitlines() if "\tunknown\t" in line]
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(fresh.splitlines())} lines")
    for line in unknown:
        print(f"no licence declared: {line}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
